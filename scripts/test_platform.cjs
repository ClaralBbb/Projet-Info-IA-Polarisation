const {chromium}=require('playwright');
const fs=require('fs'),assert=require('assert');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
 await context.route('**/*',route=>route.request().url().startsWith('http://127.0.0.1:8765/')?route.continue():route.abort());
 const page=await context.newPage(),errors=[];
 page.on('pageerror',err=>errors.push(err.message));
 await page.goto('http://127.0.0.1:8765/index.html');
 await page.waitForSelector('#results article');
 assert.equal(await page.locator('#results article').count(),10);
 assert((await page.locator('#progressText').textContent()).includes('60 / 500'));
 await page.selectOption('#status','pending');
 assert((await page.locator('#count').textContent()).startsWith('440 '));
 assert.equal(await page.locator('[data-review]').count(),0);
 await page.selectOption('#status','classified');
 await page.selectOption('#theme','interventions_policieres');
 await page.selectOption('#stance','condamne');
 assert(await page.locator('#results article').count()>0);
 await page.selectOption('#theme','');await page.selectOption('#stance','');
 await page.locator('[data-review]').first().selectOption('accord');
 await page.locator('[data-note]').first().fill('Test de relecture <b>non HTML</b>');
 await page.reload();
 await page.waitForSelector('[data-review]');
 assert.equal(await page.locator('[data-review]').first().inputValue(),'accord');
 assert.equal(await page.locator('[data-note]').first().inputValue(),'Test de relecture <b>non HTML</b>');
 const downloadPromise=page.waitForEvent('download');await page.click('#exportJson');
 const download=await downloadPromise;await download.saveAs('/tmp/relectures-platform-test.json');
 const saved=JSON.parse(fs.readFileSync('/tmp/relectures-platform-test.json','utf8'));
 assert.equal(Object.keys(saved.reviews).length,1);
 await page.locator('[data-review]').first().selectOption('desaccord');
 await page.setInputFiles('#importJson','/tmp/relectures-platform-test.json');
 await page.waitForTimeout(200);
 assert.equal(await page.locator('[data-review]').first().inputValue(),'accord');
 await page.fill('#search','introuvable-zyxwv123456789');assert.equal(await page.locator('#results article').count(),0);
 await page.fill('#search','');
 await page.evaluate(()=>localStorage.clear());await page.reload();await page.waitForSelector('#results article');
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:'/tmp/plateforme-overview.png',fullPage:false});
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:'/tmp/plateforme-mobile.png',fullPage:false});
 assert.deepEqual(errors,[]);
 console.log('Navigateur Chromium avec ressources locales seules : filtres, avancement, sauvegarde, restauration, recherche et absence d’erreurs JS validés.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
